#!/usr/bin/env node
const assert=require("assert");
const fs=require("fs");
const path=require("path");
const vm=require("vm");
const {createEngine,fold}=require("../breeding.js");
const root=path.resolve(__dirname,"..");
const document={documentElement:null,head:{appendChild(){}},addEventListener(){},querySelector(){return null;},querySelectorAll(){return[];},createElement(){return{dataset:{}};}};
const context=vm.createContext({console,window:null,document,location:{pathname:"/tests.html"},MutationObserver:class{observe(){}},URLSearchParams});
context.window=context;
for(const file of ["data.js","breeding-official-data.js","core.js"])vm.runInContext(fs.readFileSync(path.join(root,file),"utf8"),context,{filename:file});
vm.runInContext("this.resolveStandard=(a,b)=>normalChild(a,b)",context);
const engine=createEngine({pals:context.PAL_DATA,parentIds:context.PARENT_IDS,resolveChild:context.resolveStandard,uniquePairs:context.UNIQUE_PAIRS,genderRules:context.UNIQUE_GENDER_RULES});
const amnione=engine.result("clionetwins","jetdragon");
assert.strictEqual(amnione.child.id,"herculesbeetle");
assert.strictEqual(engine.result("jetdragon","clionetwins").child.id,amnione.child.id);
assert.strictEqual(engine.result("sheepball","sheepball").child.id,"sheepball");
const specialKey=Object.keys(context.UNIQUE_PAIRS).find(key=>key.split("|")[0]!==key.split("|")[1]);
assert(specialKey);
const [specialA,specialB]=specialKey.split("|"),special=engine.result(specialA,specialB);
assert.strictEqual(special.child.id,context.UNIQUE_PAIRS[specialKey]);
assert.strictEqual(special.special,true);
const reverse=engine.pairsFor(amnione.child.id);
assert(reverse.some(row=>new Set([row.a.id,row.b.id]).has("clionetwins")&&new Set([row.a.id,row.b.id]).has("jetdragon")));
assert.strictEqual(new Set(reverse.map(row=>[row.a.id,row.b.id].sort().join("|"))).size,reverse.length);
for(const row of reverse.slice(0,100))assert.strictEqual(engine.result(row.a.id,row.b.id).child.id,amnione.child.id);
assert.strictEqual(fold("Água Bênta"),"agua benta");
assert.strictEqual(fold("  LAMBALL  "),"lamball");
assert(engine.parents.every(p=>p.combiRank&&p.combiRank!==9999&&!p.isBoss));
console.log(`breeding-calculator: ${reverse.length} pares de Warsect e regras padrão/especiais aprovadas`);
